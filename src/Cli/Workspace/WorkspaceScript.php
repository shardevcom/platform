<?php

declare(strict_types=1);

namespace Shardevcom\Cli\Workspace;

/**
 * Boundary: the workspace control shell (`platform.sh`).
 *
 * `platform new` drops this script at the workspace root. It reads
 * platform.json at runtime, so it always matches the components and guards the
 * workspace actually has — including those added later with `platform add` or
 * `platform guard add` — and never has to be regenerated.
 */
final class WorkspaceScript
{
    public const FILE = 'platform.sh';

    public static function render(): string
    {
        return <<<'BASH'
#!/usr/bin/env bash
#
# platform.sh — control shell for this Shardev workspace.
#
# Generated by `platform new`. Reads platform.json at runtime, so it always
# matches the components and guards this workspace actually has (including those
# added later with `platform add` / `platform guard add`).
#
# Usage: ./platform.sh <command> [target] [guard...]
# Run `./platform.sh help` for the full list.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MANIFEST="$ROOT/platform.json"
STATE_DIR="$ROOT/.platform"
RUN_DIR="$STATE_DIR/run"
LOG_DIR="$STATE_DIR/logs"

API_PORT="${API_PORT:-8000}"
API_HOST="${API_HOST:-http://localhost:${API_PORT}}"
MOBILE_API_HOST="${MOBILE_API_HOST:-http://10.0.2.2:${API_PORT}}"
MOBILE_DEVICE="${MOBILE_DEVICE:-}"

if [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
  C_RESET=$'\033[0m'; C_DIM=$'\033[2m'; C_BOLD=$'\033[1m'
  C_RED=$'\033[31m'; C_GREEN=$'\033[32m'; C_YELLOW=$'\033[33m'; C_CYAN=$'\033[36m'
else
  C_RESET=''; C_DIM=''; C_BOLD=''; C_RED=''; C_GREEN=''; C_YELLOW=''; C_CYAN=''
fi

ISSUES=0

say()  { printf '%s\n' "$*"; }
info() { printf '%s==>%s %s\n' "$C_CYAN" "$C_RESET" "$*"; }
ok()   { printf '%sok%s  %s\n' "$C_GREEN" "$C_RESET" "$*"; }
warn() { printf '%s!%s   %s\n' "$C_YELLOW" "$C_RESET" "$*" >&2; }
err()  { printf '%serr%s %s\n' "$C_RED" "$C_RESET" "$*" >&2; }
die()  { err "$*"; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }
rel()  { printf '%s' "${1#"$ROOT"/}"; }

# ---------------------------------------------------------------- manifest ---

require_manifest() {
  [ -f "$MANIFEST" ] || die "platform.json not found in $ROOT (is this a workspace root?)"
  have php || die "php is required to read platform.json"
}

component_names() {
  php -r '$d=json_decode((string)file_get_contents($argv[1]),true);echo implode(" ",array_keys($d["components"]??[]));' "$MANIFEST"
}

component_field() { # <name> <path|guards|enabled>
  php -r '
    $d=json_decode((string)file_get_contents($argv[1]),true);
    $c=$d["components"][$argv[2]]??null;
    if($c===null){exit(0);}
    switch($argv[3]){
      case "path": echo $c["path"]??$argv[2]; break;
      case "guards": echo implode(" ",array_map("strval",$c["guards"]??[])); break;
      case "enabled": echo !empty($c["enabled"])?"1":"0"; break;
    }
  ' "$MANIFEST" "$1" "$2"
}

workspace_name() {
  php -r '$d=json_decode((string)file_get_contents($argv[1]),true);echo $d["name"]??"";' "$MANIFEST"
}

has_component() { component_names | tr ' ' '\n' | grep -qx "$1"; }
comp_path()     { component_field "$1" path; }
comp_guards()   { component_field "$1" guards; }
comp_enabled()  { [ "$(component_field "$1" enabled)" = "1" ]; }

all_guards() {
  php -r '$d=json_decode((string)file_get_contents($argv[1]),true);$g=[];foreach(($d["components"]??[]) as $c){foreach(($c["guards"]??[]) as $x){$g[(string)$x]=1;}}echo implode(" ",array_keys($g));' "$MANIFEST"
}

app_for_guard() { if [ "$1" = "web" ]; then printf 'user'; else printf '%s' "$1"; fi; }

first_guard() {
  local guards; guards="$(comp_guards "$1")"
  if [ -n "$guards" ]; then set -- $guards; printf '%s' "$1"
  elif [ -n "$(all_guards)" ]; then set -- $(all_guards); printf '%s' "$1"
  else printf 'web'; fi
}

guard_list_for() {
  local guards; guards="$(comp_guards "$1")"
  if [ -n "$guards" ]; then printf '%s' "$guards"; else all_guards; fi
}

web_port() { # <app>
  local cfg="$ROOT/$(comp_path web)/apps/$1/vite.config.ts"
  [ -f "$cfg" ] || return 0
  sed -n 's/.*createAppConfig([^,]*,[[:space:]]*\([0-9][0-9]*\)).*/\1/p' "$cfg" | head -n1
}

# ------------------------------------------------------------------- state ---

pid_file() { printf '%s/%s.pid' "$RUN_DIR" "$1"; }
log_file() { printf '%s/%s.log' "$LOG_DIR" "$1"; }
running()  { [ -f "$1" ] && kill -0 "$(cat "$1")" 2>/dev/null; }
running_target() { running "$(pid_file "$1")"; }

kill_tree() { # <pid> [signal]
  local pid="$1" sig="${2:-TERM}" child
  for child in $(pgrep -P "$pid" 2>/dev/null); do kill_tree "$child" "$sig"; done
  kill -"$sig" "$pid" 2>/dev/null || true
}

launch() { # <target> <dir> <cmd...>
  local target="$1" dir="$2"; shift 2
  mkdir -p "$RUN_DIR" "$LOG_DIR"
  if running_target "$target"; then
    warn "$target already running (pid $(cat "$(pid_file "$target")"))"
    return 0
  fi
  if [ ! -d "$dir" ]; then
    err "$target: missing directory $(rel "$dir")"
    return 1
  fi
  local log; log="$(log_file "$target")"
  : >"$log"
  info "start $C_BOLD$target$C_RESET: $*"
  if have setsid; then
    ( cd "$dir" && setsid "$@" >"$log" 2>&1 </dev/null & echo $! >"$(pid_file "$target")" )
  else
    ( cd "$dir" && "$@" >"$log" 2>&1 </dev/null & echo $! >"$(pid_file "$target")" )
  fi
  sleep 0.5
  if ! running_target "$target"; then
    err "$target failed to start; last log lines:"
    tail -n 15 "$log" >&2 || true
    rm -f "$(pid_file "$target")"
    return 1
  fi
  ok "$target up (pid $(cat "$(pid_file "$target")"))  log: $(rel "$log")"
}

stop_target() {
  local target="$1" file pid i
  file="$(pid_file "$target")"
  if [ ! -f "$file" ]; then warn "$target not running"; return 0; fi
  pid="$(cat "$file")"
  if kill -0 "$pid" 2>/dev/null; then
    kill_tree "$pid" TERM
    for i in $(seq 1 25); do kill -0 "$pid" 2>/dev/null || break; sleep 0.2; done
    kill -0 "$pid" 2>/dev/null && kill_tree "$pid" KILL
    ok "stopped $target (pid $pid)"
  else
    warn "$target had a stale pid ($pid)"
  fi
  rm -f "$file"
}

stop_all() {
  local file target found=0
  for file in "$RUN_DIR"/*.pid; do
    [ -e "$file" ] || continue
    target="$(basename "$file" .pid)"
    stop_target "$target"; found=1
  done
  [ "$found" = 1 ] || warn "nothing is running"
}

# ---------------------------------------------------------------- commands ---

cmd_api() {
  has_component api || die "this workspace has no api component"
  launch api "$ROOT/$(comp_path api)" php artisan serve --host=0.0.0.0 --port="$API_PORT"
}

cmd_web() {
  has_component web || die "this workspace has no web component"
  local guards=("$@") guard app rc=0
  if [ ${#guards[@]} -eq 0 ]; then read -r -a guards <<<"$(guard_list_for web)"; fi
  for guard in "${guards[@]}"; do
    app="$(app_for_guard "$guard")"
    launch "web:$guard" "$ROOT/$(comp_path web)" npm run "dev:$app" || rc=1
  done
  return $rc
}

cmd_desktop() {
  has_component desktop || die "this workspace has no desktop component"
  local guards=("$@") guard app rc=0
  if [ ${#guards[@]} -eq 0 ]; then read -r -a guards <<<"$(guard_list_for desktop)"; fi
  for guard in "${guards[@]}"; do
    app="$(app_for_guard "$guard")"
    launch "desktop:$guard" "$ROOT/$(comp_path desktop)" ./gradlew ":apps:$app:run" || rc=1
  done
  return $rc
}

cmd_mobile() {
  has_component mobile || die "this workspace has no mobile component"
  local guard="${1:-$(first_guard mobile)}"
  cd "$ROOT/$(comp_path mobile)" || die "cannot enter mobile/"
  info "flutter run (guard=$guard, api=$MOBILE_API_HOST)"
  # shellcheck disable=SC2086
  flutter run --dart-define=GUARD="$guard" --dart-define=API_HOST="$MOBILE_API_HOST" ${MOBILE_DEVICE:+-d "$MOBILE_DEVICE"}
}

cmd_up() {
  local targets=("$@") target
  if [ ${#targets[@]} -eq 0 ]; then
    targets=()
    has_component api && targets+=(api)
    has_component web && targets+=(web)
  fi
  for target in "${targets[@]}"; do
    case "$target" in
      api) cmd_api ;;
      web) cmd_web ;;
      mobile) cmd_mobile ;;
      desktop) cmd_desktop ;;
      *) warn "unknown target: $target" ;;
    esac
  done
}

cmd_stop() {
  if [ $# -eq 0 ]; then stop_all; return; fi
  local target guard
  for target in "$@"; do
    case "$target" in
      api) stop_target api ;;
      web) for guard in $(guard_list_for web); do stop_target "web:$guard"; done ;;
      desktop) for guard in $(guard_list_for desktop); do stop_target "desktop:$guard"; done ;;
      mobile) warn "mobile runs in the foreground; stop it with Ctrl-C" ;;
      *) stop_target "$target" ;;
    esac
  done
}

cmd_restart() {
  if [ $# -eq 0 ]; then stop_all; cmd_up; return; fi
  cmd_stop "$@"
  cmd_up "$@"
}

cmd_status() {
  require_manifest
  local name enabled guards any=0 guard app port
  say "${C_BOLD}$(workspace_name)${C_RESET}  ${C_DIM}$ROOT${C_RESET}"
  say ""
  say "${C_BOLD}Components${C_RESET}"
  for name in $(component_names); do
    guards="$(comp_guards "$name")"
    if comp_enabled "$name"; then enabled="${C_GREEN}on${C_RESET}"; else enabled="${C_DIM}off${C_RESET}"; fi
    printf '  %-8s %s  %-12s %sguards: %s%s\n' "$name" "$enabled" "$(comp_path "$name")/" "$C_DIM" "${guards:-none}" "$C_RESET"
  done
  say ""
  say "${C_BOLD}Processes${C_RESET}"
  if has_component api; then
    any=1
    if running_target api; then ok "api          up   pid $(cat "$(pid_file api)")   $API_HOST"
    else printf '  %sapi          down%s %s\n' "$C_DIM" "$C_RESET" "$API_HOST"; fi
  fi
  if has_component web; then
    any=1
    for guard in $(guard_list_for web); do
      app="$(app_for_guard "$guard")"; port="$(web_port "$app")"
      if running_target "web:$guard"; then ok "web:$guard      up   pid $(cat "$(pid_file "web:$guard")")   http://localhost:${port:-?}"
      else printf '  %sweb:%-8s down%s http://localhost:%s\n' "$C_DIM" "$guard" "$C_RESET" "${port:-?}"; fi
    done
  fi
  if has_component desktop; then
    any=1
    for guard in $(guard_list_for desktop); do
      if running_target "desktop:$guard"; then ok "desktop:$guard  up   pid $(cat "$(pid_file "desktop:$guard")")"
      else printf '  %sdesktop:%-4s down%s\n' "$C_DIM" "$guard" "$C_RESET"; fi
    done
  fi
  if has_component mobile; then
    any=1
    printf '  %smobile        foreground only%s ./platform.sh mobile\n' "$C_DIM" "$C_RESET"
  fi
  [ "$any" = 1 ] || say "  ${C_DIM}(nothing to run)${C_RESET}"
}

cmd_logs() {
  local target="${1:-}"
  if [ -z "$target" ]; then
    say "logs in $(rel "$LOG_DIR")/"
    ls -1 "$LOG_DIR" 2>/dev/null | sed 's/^/  /' || say "  (none)"
    return
  fi
  local file; file="$(log_file "$target")"
  [ -f "$file" ] || die "no log for '$target'"
  tail -n 60 -f "$file"
}

cmd_build() {
  require_manifest
  local targets=("$@") name guard dir rc=0
  if [ ${#targets[@]} -eq 0 ]; then read -r -a targets <<<"$(component_names)"; fi
  for name in "${targets[@]}"; do
    has_component "$name" || { warn "unknown component: $name"; continue; }
    dir="$ROOT/$(comp_path "$name")"
    case "$name" in
      api) info "build api (composer dump-autoload)"; ( cd "$dir" && composer dump-autoload -o ) || rc=1 ;;
      web)
        if [ -n "$(comp_guards web)" ]; then
          for guard in $(guard_list_for web); do
            info "build web:$guard"
            ( cd "$dir" && npm run "build:$(app_for_guard "$guard")" ) || rc=1
          done
        else
          info "build web"; ( cd "$dir" && npm run build ) || rc=1
        fi ;;
      mobile) info "build mobile (flutter build apk --debug)"; ( cd "$dir" && flutter build apk --debug ) || rc=1 ;;
      desktop) info "build desktop (gradlew build)"; ( cd "$dir" && ./gradlew build ) || rc=1 ;;
    esac
  done
  if [ "$rc" = 0 ]; then ok "build done"; else warn "build finished with errors"; fi
  return $rc
}

cmd_install() {
  require_manifest
  local targets=("$@") name dir rc=0
  if [ ${#targets[@]} -eq 0 ]; then read -r -a targets <<<"$(component_names)"; fi
  for name in "${targets[@]}"; do
    has_component "$name" || { warn "unknown component: $name"; continue; }
    dir="$ROOT/$(comp_path "$name")"
    case "$name" in
      api) info "install api (composer install)"; ( cd "$dir" && composer install ) || rc=1 ;;
      web) info "install web (npm install)"; ( cd "$dir" && npm install ) || rc=1 ;;
      mobile) info "install mobile (flutter pub get)"; ( cd "$dir" && flutter pub get ) || rc=1 ;;
      desktop) info "install desktop (gradlew -x test)"; ( cd "$dir" && ./gradlew build -x test ) || rc=1 ;;
    esac
  done
  if [ "$rc" = 0 ]; then ok "install done"; else warn "install finished with errors"; fi
  return $rc
}

pass() { printf '  %sok%s  %s\n' "$C_GREEN" "$C_RESET" "$1"; }
fail() {
  printf '  %s!!%s  %s\n' "$C_RED" "$C_RESET" "$1"
  [ -n "${2:-}" ] && printf '        %s-> %s%s\n' "$C_DIM" "$2" "$C_RESET"
  ISSUES=$((ISSUES + 1))
}
check_tool() { if have "$1"; then pass "$1 ($("$1" --version 2>&1 | head -n1))"; else fail "$1 not found" "${2:-install $1}"; fi }

cmd_doctor() {
  require_manifest
  ISSUES=0
  local name dir
  say "${C_BOLD}Toolchain${C_RESET}"
  check_tool php "install PHP 8.2+"
  check_tool composer "https://getcomposer.org"
  if has_component web; then check_tool node "install Node.js 20+"; check_tool npm "install Node.js 20+"; fi
  if has_component mobile; then check_tool flutter "https://docs.flutter.dev/get-started/install"; check_tool dart "ships with Flutter"; fi
  if has_component desktop; then check_tool java "install JDK 21+"; fi
  say ""
  say "${C_BOLD}Components${C_RESET}"
  for name in $(component_names); do
    dir="$ROOT/$(comp_path "$name")"
    if [ ! -d "$dir" ]; then fail "$name/ missing" "listed in platform.json but not on disk"; continue; fi
    case "$name" in
      api)
        if [ -f "$dir/.env" ]; then pass "api/.env"; else fail "api/.env missing" "cd $(comp_path api) && cp .env.example .env && php artisan key:generate"; fi
        if [ -d "$dir/vendor" ]; then pass "api/vendor"; else fail "api dependencies not installed" "cd $(comp_path api) && composer install"; fi
        if [ -f "$dir/database/database.sqlite" ]; then pass "api sqlite database"; else fail "api sqlite database missing" "cd $(comp_path api) && touch database/database.sqlite && php artisan migrate"; fi
        ;;
      web)
        if [ -d "$dir/node_modules" ]; then pass "web/node_modules"; else fail "web dependencies not installed" "cd $(comp_path web) && npm install"; fi
        ;;
      mobile)
        if [ -d "$dir/.dart_tool" ]; then pass "mobile/.dart_tool"; else fail "mobile dependencies not fetched" "cd $(comp_path mobile) && flutter pub get"; fi
        ;;
      desktop)
        if [ -x "$dir/gradlew" ]; then pass "desktop/gradlew"; else fail "desktop gradle wrapper missing or not executable" "chmod +x $(comp_path desktop)/gradlew"; fi
        ;;
    esac
  done
  say ""
  if [ "$ISSUES" = 0 ]; then ok "no problems detected"; else warn "$ISSUES issue(s) found — run ./platform.sh fix"; return 1; fi
}

cmd_fix() {
  require_manifest
  local dir
  info "applying safe fixes"
  if has_component api; then
    dir="$ROOT/$(comp_path api)"
    if [ ! -f "$dir/.env" ] && [ -f "$dir/.env.example" ]; then cp "$dir/.env.example" "$dir/.env" && ok "created api/.env"; fi
    if [ ! -d "$dir/vendor" ]; then ( cd "$dir" && composer install ) || warn "composer install failed"; fi
    if [ -f "$dir/.env" ]; then ( cd "$dir" && php artisan key:generate --force >/dev/null 2>&1 || true ); fi
    if [ -d "$dir/database" ]; then
      touch "$dir/database/database.sqlite"
      ( cd "$dir" && php artisan migrate --force ) || warn "migrate failed"
    fi
  fi
  if has_component web && [ ! -d "$ROOT/$(comp_path web)/node_modules" ]; then ( cd "$ROOT/$(comp_path web)" && npm install ) || warn "npm install failed"; fi
  if has_component mobile && [ ! -d "$ROOT/$(comp_path mobile)/.dart_tool" ]; then ( cd "$ROOT/$(comp_path mobile)" && flutter pub get ) || warn "flutter pub get failed"; fi
  if has_component desktop; then dir="$ROOT/$(comp_path desktop)"; [ -x "$dir/gradlew" ] || chmod +x "$dir/gradlew" 2>/dev/null || true; fi
  ok "fixes applied"
}

cmd_help() {
  cat <<'USAGE'
platform.sh — control shell for this Shardev workspace

Usage: ./platform.sh <command> [target] [guard...]

Run / servers:
  up [target...]      Start the API and web clients (default: api web)
  api                 Start the API (php artisan serve)
  web [guard...]      Start one Vite dev server per guard (default: all)
  desktop [guard...]  Run one JavaFX app per guard (default: all)
  mobile [guard]      Run the Flutter app (foreground) for one guard
  stop [target...]    Stop background servers (default: all)
  restart [target...] Restart servers
  status              Components, guards, ports and running processes (alias: ps)
  logs [target]       Tail a server log (no target: list logs)

Build / dependencies:
  build [target...]   Build components (default: all)
  install [target...] Install dependencies (default: all)

Health:
  doctor              Check toolchain, deps, config and ports (alias: check)
  fix                 Apply safe fixes (install deps, .env, key, migrate)

Environment:
  API_PORT=8000        API port (default 8000)
  API_HOST=...         API URL used by clients
  MOBILE_API_HOST=...  API URL baked into the mobile build (10.0.2.2 for emulator)
  MOBILE_DEVICE=<id>   flutter -d target
  NO_COLOR=1           Disable colors

Examples:
  ./platform.sh up                    # API + every web guard
  ./platform.sh web admin             # only the admin web app
  ./platform.sh desktop employee
  ./platform.sh stop && ./platform.sh status
USAGE
}

# ------------------------------------------------------------------ router ---

cmd="${1:-help}"
if [ $# -gt 0 ]; then shift; fi

case "$cmd" in
  help|-h|--help) cmd_help ;;
  up|start)       cmd_up "$@" ;;
  api)            cmd_api "$@" ;;
  web)            cmd_web "$@" ;;
  mobile)         cmd_mobile "$@" ;;
  desktop)        cmd_desktop "$@" ;;
  stop|down)      cmd_stop "$@" ;;
  restart)        cmd_restart "$@" ;;
  status|ps)      cmd_status ;;
  logs|log)       cmd_logs "$@" ;;
  build)          cmd_build "$@" ;;
  install)        cmd_install "$@" ;;
  doctor|check)   cmd_doctor ;;
  fix|repair)     cmd_fix ;;
  *) err "unknown command: $cmd"; say ""; cmd_help; exit 1 ;;
esac
BASH;
    }
}
